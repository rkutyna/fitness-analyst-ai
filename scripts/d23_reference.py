def self_check(doc: dict) -> None:
    """Replay the file the way the other language will, and fail loudly."""
    for case in doc["cases"]:
        if "wire_b64" not in case:
            continue
        wire = base64.b64decode(case["wire_b64"])
        assert hashlib.sha256(wire).hexdigest() == case["wire_sha256"], case["name"]
        assert len(wire) == case["wire_length"], case["name"]
    large = [c for c in doc["cases"] if c["name"] == "request_large_1_2mb"][0]
    body = large_body()
    assert hashlib.sha256(body).hexdigest() == large["plaintext_sha256"]
    # Every `ok` case must actually open under the published parameters.
    for case in doc["cases"]:
        if case["expected"] != "ok":
            continue
        wire = (base64.b64decode(case["wire_b64"]) if "wire_b64" in case
                else seal(VECTOR_SECRET, case["direction"], case["method"],
                          case["target"].encode("utf-8"), body,
                          case["timestamp_ms"],
                          base64.b64decode(case["nonce_b64"]))[0])
        aad = base64.b64decode(case["aad_b64"])
        plain = AESGCM(body_key(VECTOR_SECRET, case["direction"])).decrypt(
            wire[9:21], wire[21:], aad)
        assert hashlib.sha256(plain).hexdigest() == case["plaintext_sha256"], \
            case["name"]
    print(f"self-check ok: {len(doc['cases'])} cases, "
          f"{sum(1 for c in doc['cases'] if c['expected'] == 'ok')} ok, "
          f"{sum(1 for c in doc['cases'] if c['expected'] != 'ok')} negative")


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out", type=Path, required=True)
    args = ap.parse_args(argv)
    doc = build_document()
    self_check(doc)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(json.dumps(doc, indent=2, ensure_ascii=False) + "\n",
                        encoding="utf-8")
    print(f"wrote {args.out} ({args.out.stat().st_size} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
