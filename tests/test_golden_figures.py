def test_published_vo2_and_easy_block_figures(golden_conn, tmp_path):
    # week-04-review.md:57; 0.1 mL/min·kg matches the published one-decimal VO2.
    assert _daily_metric(
        golden_conn, "vo2_max", "2026-07-26", "2026-07-26", "last"
    )[0] == pytest.approx(37.4, abs=0.1)

    weekly_vo2 = A.weekly_series(
        golden_conn, "vo2_max", "2026-07-27", "2026-08-02"
    )[0]
    # week-05-review.md:53; 0.1 mL/min·kg matches the published one-decimal mean.
    assert weekly_vo2["mean"] == pytest.approx(37.4, abs=0.1)

    sun_w7 = _workout(golden_conn, "2026-08-15", "running")
    block = A.longest_block(
        golden_conn, sun_w7["start_utc"], sun_w7["end_utc"]
    )
    # The published figures are 9.0 min at HR 146 (week-07-review.md:42), read
    # while the block dial still had a pace lane. The one jog rule (#604) has no
    # pace lane: a bucket is jog on cadence (or a near-running cadence at a
    # running heart rate), and this golden slice deliberately omits step_count --
    # golden_snapshot.py's _RECORD_METRICS excludes it so that
    # test_published_jog_minutes_and_pace's four historical weeks stay pinned at
    # 0.0 jog_minutes (an explicit #193-era "historical and immutable" decision;
    # adding it flips those weeks to non-zero). On a cadence-blind slice no
    # bucket can be jog, so the measured block is none: None / None / 0.0
    # (were 9.0 / 146.0 / 9.0). The session itself, with its step data, reads
    # 9.7 min at HR 144.6 on the full reference vault under both the three-lane
    # predicate (#467) and the one rule; that is where the figure is checked.
    assert block["qualified_min"] is None
    assert block["avg_hr_longest_block"] is None
    assert block["bridged_min"] == pytest.approx(0.0, abs=0.1)

    # Positive control: the zeros above are what a slice with no cadence reads,
    # and a broken rule reads them too. Put a synthetic 150 steps/min stream into
    # exactly the buckets the retired pace lane counted on this session and the
    # block must come back -- the published 9.0 min at HR 146 -- through the one
    # rule's cadence lane alone.
    cadenced, seeded = _cadenced_copy(
        golden_conn, tmp_path,
        [(sun_w7["start_utc"], sun_w7["end_utc"])], retired_pace_lane_only=True)
    try:
        assert seeded
        again = A.longest_block(
            cadenced, sun_w7["start_utc"], sun_w7["end_utc"])
        # week-07-review.md:42; same tolerances as the original assertions.
        assert again["qualified_min"] == pytest.approx(9.0, abs=0.1)
        assert again["avg_hr_longest_block"] == pytest.approx(146.0, abs=0.5)
        assert again["bridged_min"] == pytest.approx(9.0, abs=0.1)
    finally:
        cadenced.close()
